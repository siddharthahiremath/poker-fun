"""Reproduce Logan's standalone file without unpacking any opponent source.

The opaque Riaan file is copied unchanged and used through its public Agent API.
The model contains numeric estimates learned offline from normal match actions.
"""

import argparse
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    metadata = json.loads((ROOT / "bench/logan_data/metadata.json").read_text())
    base = (ROOT / "agents/riaan.py").read_bytes()
    digest = hashlib.sha256(base).hexdigest()
    if digest != metadata["base_sha256"]:
        raise ValueError("Riaan's source changed: revalidate before rebuilding this trained policy")
    model = (ROOT / "bench/logan_data/model.json.zlib").read_bytes()
    if hashlib.sha256(model).hexdigest() != metadata["model_zlib_sha256"]:
        raise ValueError("Model checksum mismatch")
    packed = base64.b85encode(model)
    header = ('"""Logan: opaque Riaan base plus public-info action adjustments.\n'
              f'Base SHA-256: {digest}\nGenerated by scripts/build_blackbox.py.\n"""\n'
              f'_ORIGINAL_SOURCE = {base!r}\n'
              '_base_globals = {"__name__": __name__ + "_opaque_base", "__file__": __file__}\n'
              'exec(compile(_ORIGINAL_SOURCE, "<unchanged-riaan>", "exec"), _base_globals)\n'
              '_BaseAgent = _base_globals["Agent"]\n'
              f'CONFIG = {metadata["config"]!r}\n'
              f'_PERCENTILES = {tuple(metadata["percentiles"])!r}\n\n'
              'import base64 as _base64, zlib as _zlib, json as _json\n'
              f'_MODEL = _json.loads(_zlib.decompress(_base64.b85decode({packed!r})))\n')
    return header + (ROOT / "bench/logan_policy.py").read_text()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-o", "--output", type=Path, default=ROOT / "agents/logan.py")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    source = build()
    if args.check:
        if args.output.read_text() != source:
            raise SystemExit("Standalone file does not match its policy, model, and opaque base")
        print("Standalone file matches its source and model")
    else:
        args.output.write_text(source)
        print(f"Wrote {args.output} ({len(source.encode()):,} bytes)")


if __name__ == "__main__":
    main()
